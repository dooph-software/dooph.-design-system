// Spacing-scale rename (maintainer's Figma token change, 2026-10-03).
// Deterministic, single pass (no chained renames). Default is a dry run; pass --write to apply.
// Mapping derived by Figma variable ID: old export (git b436647 figma-variable-jsons/Sizing_Spacing.json)
// → new export (Downloads/Sizing_Spacing.json). See docs/audit/figma-additions.md.
// Usage (repo root): node docs/audit/_work/scratch/token-pass/spacing-rename.mjs [--write]
// After --write: set the new token values in tokens.css (this script does that too), then `npm run sync-tokens`.
import fs from 'node:fs';
import path from 'node:path';

const WRITE = process.argv.includes('--write');
// NOT idempotent: a second run would shift every name again. Refuse once the new scale exists.
if (/--ui-spacing-xxxl\s*:/.test(fs.readFileSync('src/styles/tokens.css', 'utf8'))) {
  console.error('Refusing: tokens.css already has --ui-spacing-xxxl, so the rename was already applied (2026-10-03).');
  process.exit(1);
}
const MAP = { xxxs: 'xxxs', xxs: 'xxs', xs: 'sm', sm: 'rg', rg: 'md', md: 'lg', lg: 'xl', xl: 'xxl', xxl: 'xxxl' };
const OLD_PX = { xxxs: 2, xxs: 4, xs: 8, sm: 10, rg: 12, md: 16, lg: 20, xl: 28, xxl: 40 };
const NAMES = 'xxxs|xxs|xs|sm|rg|md|lg|xl|xxl';

// Tailwind utilities that read the --spacing-* theme namespace.
const TW = [
  'p', 'px', 'py', 'pt', 'pr', 'pb', 'pl', 'ps', 'pe',
  'm', 'mx', 'my', 'mt', 'mr', 'mb', 'ml', 'ms', 'me',
  'gap', 'gap-x', 'gap-y', 'space-x', 'space-y',
  'inset', 'inset-x', 'inset-y', 'top', 'right', 'bottom', 'left', 'start', 'end',
  'w', 'h', 'size', 'min-w', 'min-h', 'max-w', 'max-h', 'basis',
  'translate-x', 'translate-y', 'indent',
  'scroll-m', 'scroll-mx', 'scroll-my', 'scroll-mt', 'scroll-mr', 'scroll-mb', 'scroll-ml',
  'scroll-p', 'scroll-px', 'scroll-py', 'scroll-pt', 'scroll-pr', 'scroll-pb', 'scroll-pl',
];
// DS helper classes named after the spacing step, e.g. .ds-px-ui-sm { padding-inline: var(--ui-spacing-sm) }
const DS = '(?:ds-(?:p|px|py|pt|pr|pb|pl|m|mx|my|mt|mr|mb|ml|gap)-ui)';
const twAlt = TW.slice().sort((a, b) => b.length - a.length).map((s) => s.replace(/-/g, '\\-')).join('|');

const reClass = new RegExp(`(?<![\\w-])(-?)(${twAlt}|${DS})-(${NAMES})(?![\\w-])`, 'g');
const reVar = new RegExp(`(--ui-spacing-)(${NAMES})(?![\\w-])`, 'g');
// Comments/JSDoc that pair a step name with its px, e.g. "`md` (16px)" or "md (16px)" or "spacing-md (16px)".
const reComment = new RegExp('(`?)\\b(' + NAMES + ')\\b(`?)(\\s*\\(\\s*)(\\d+)px', 'g');

const ROOTS = ['src', '.storybook'];
const EXT = new Set(['.ts', '.tsx', '.css', '.mdx', '.js', '.mjs']);
const SKIP = new Set([path.normalize('src/styles/theme.css')]); // generated by sync-theme.mjs
const files = [];
const walk = (d) => {
  if (!fs.existsSync(d)) return;
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) { if (e.name !== 'node_modules') walk(p); }
    else if (EXT.has(path.extname(e.name)) && !SKIP.has(path.normalize(p))) files.push(p);
  }
};
ROOTS.forEach(walk);

const tally = {};
const commentHits = [];
let changedFiles = 0;
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  // Leave the generated @theme block alone; sync-tokens regenerates it.
  const G0 = src.indexOf('__GENERATED_THEME_START__');
  const G1 = src.indexOf('__GENERATED_THEME_END__');
  const segs = G0 >= 0 && G1 > G0 ? [[0, G0, true], [G0, G1, false], [G1, src.length, true]] : [[0, src.length, true]];
  let out = '';
  let n = 0;
  for (const [a, b, edit] of segs) {
    let s = src.slice(a, b);
    if (edit) {
      s = s.replace(reClass, (m, neg, pre, name) => { n++; const k = `${pre}-${name}→${MAP[name]}`; tally[k] = (tally[k] || 0) + 1; return `${neg}${pre}-${MAP[name]}`; });
      s = s.replace(reVar, (m, pre, name) => { n++; const k = `--ui-spacing-${name}→${MAP[name]}`; tally[k] = (tally[k] || 0) + 1; return `${pre}${MAP[name]}`; });
      s = s.replace(reComment, (m, b1, name, b2, mid, px) => {
        if (OLD_PX[name] !== Number(px)) return m; // only rewrite when the px proves it means the spacing step
        n++; commentHits.push(`${f}: ${m.trim()} → ${b1}${MAP[name]}${b2}${mid}${px}px`);
        return `${b1}${MAP[name]}${b2}${mid}${px}px`;
      });
    }
    out += s;
  }
  if (n) {
    changedFiles++;
    if (WRITE) fs.writeFileSync(f, out);
  }
}

// Token values in tokens.css: insert the new 6px `xs`, and apply the two values Figma changed.
const T = 'src/styles/tokens.css';
let t = fs.readFileSync(T, 'utf8');
if (WRITE) {
  if (!/--ui-spacing-xs:\s*6px/.test(t)) t = t.replace(/(\n(\s*)--ui-spacing-xxs:\s*4px;)/, '$1\n$2--ui-spacing-xs: 6px;');
  t = t.replace(/--ui-spacing-xxl:\s*28px;/, '--ui-spacing-xxl: 26px;');
  t = t.replace(/--ui-spacing-xxxl:\s*40px;/, '--ui-spacing-xxxl: 42px;');
  fs.writeFileSync(T, t);
}

console.log(`${WRITE ? 'WROTE' : 'DRY RUN'} — files scanned ${files.length}, files changed ${changedFiles}`);
for (const [k, v] of Object.entries(tally).sort()) console.log(`  ${k}: ${v}`);
console.log(`comment px-pairs rewritten: ${commentHits.length}`);
for (const c of commentHits) console.log('  ' + c);
