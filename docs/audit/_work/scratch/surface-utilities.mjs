#!/usr/bin/env node
// surface-utilities.mjs <matched.json> <out.md>
//
// Attributes every "generated utilities" line of api-diff to the files that
// write (or wrote) the class. dist/styles.css is compiled by Tailwind v4,
// whose automatic source detection scans every non-ignored file of the
// project — not only the explicit `@source` (src/**, stories included). So a
// utility appears or disappears when some file starts or stops writing it,
// and that file may be a doc or a scratch file. For each line: the tree
// searched (b436647 for a change that landed before it, HEAD / v5.3.0
// otherwise), the files holding the class, and, for changes after b436647,
// the CHANGES.md entries that name one of the src/ files.

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, basename } from 'node:path';

const ROOT = 'C:/Users/stick/Github/dooph';
const TREES = { v530: `${ROOT}/ds-v530`, b43: `${ROOT}/ds-v530/_b436647`, head: `${ROOT}/ds-head` };
const [matchedP, outP] = process.argv.slice(2);
const lines = JSON.parse(readFileSync(matchedP, 'utf8')).filter((l) => /generated utilities/.test(l.section));

// node_modules / dist are gitignored (Tailwind skips them); .git and the
// nested b436647 export were not present when those trees were built.
const SKIP = new Set(['node_modules', 'dist', '.git', '_b436647', 'storybook-static']);
const BINARY = /\.(png|jpe?g|gif|webp|ico|woff2?|ttf|otf|pdf|zip|tgz)$/i;
function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    if (SKIP.has(n)) continue;
    const p = join(dir, n);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (st.size < 8e6 && !BINARY.test(n)) out.push(p);
  }
  return out;
}
const files = {};
for (const [k, t] of Object.entries(TREES)) {
  files[k] = walk(t).map((p) => ({ rel: relative(t, p).split('\\').join('/'), text: readFileSync(p, 'utf8') }));
}
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
function usersOf(tree, cls) {
  const re = new RegExp(`(^|[\\s"'\`{(,>])${esc(cls)}($|[\\s"'\`}),<.;!?])`);
  return files[tree].filter((f) => re.test(f.text)).map((f) => f.rel);
}

const changes = readFileSync(`${ROOT}/dooph-Design-System/docs/audit/CHANGES.md`, 'utf8');
const entries = [];
{
  let cur = null;
  changes.split(/\r?\n/).forEach((ln, i) => {
    const h = ln.match(/^### (.*)/);
    if (h) { cur = { heading: h[1], line: i + 1, body: '' }; entries.push(cur); }
    else if (cur) cur.body += ln + '\n';
  });
}
const entriesNaming = (rel) => entries.filter((e) => e.body.includes(basename(rel))).map((e) => `${e.line}: ${e.heading.slice(0, 60)}`);

const rows = [];
const tally = {};
for (const l of lines) {
  const m = l.text.match(/^- `\.(.+)` (added|removed)$/);
  const cls = m[1], dir = m[2];
  const tree = l.when === 'pre' ? (dir === 'added' ? 'b43' : 'v530') : dir === 'added' ? 'head' : 'b43';
  const users = usersOf(tree, cls);
  const inSrc = users.filter((u) => u.startsWith('src/'));
  let kind;
  if (!users.length) kind = 'no hit anywhere';
  else if (!inSrc.length) kind = 'outside src/ only (docs/scratch, picked up by automatic source detection)';
  else if (inSrc.every((u) => /\.stories\.tsx$/.test(u))) kind = 'stories only';
  else if (inSrc.every((u) => u.endsWith('.css'))) kind = 'defined in a stylesheet';
  else kind = 'component source';
  const named = l.when === 'pre' ? [] : [...new Set(inSrc.flatMap(entriesNaming))];
  const key = `${l.when} | ${dir} | ${kind}${l.when !== 'pre' && inSrc.length ? (named.length ? ' | file named in CHANGES.md' : ' | file not named in CHANGES.md') : ''}`;
  tally[key] = (tally[key] ?? 0) + 1;
  rows.push({ cls, dir, when: l.when, tree, users, inSrc, kind, named });
}

let md = `# Generated-utility attribution (api-diff "generated utilities" section)\n\n`;
md += `Generated by \`docs/audit/_work/scratch/surface-utilities.mjs\`. A utility class is in \`dist/styles.css\` because some file of the built tree writes it: Tailwind v4's automatic source detection scans every file git does not ignore, on top of the explicit \`@source "../**/*.{js,ts,jsx,tsx}"\` (which includes stories). For each api-diff line: the tree searched (the side of the change where the class exists; b436647 for a change that landed before it), the files holding it, and for a change after b436647 the CHANGES.md entries naming one of its src/ files.\n\n`;
md += `| when | direction | where the class comes from | lines |\n|---|---|---|---|\n`;
for (const [k, n] of Object.entries(tally).sort()) { const [w, d, ...rest] = k.split(' | '); md += `| ${w} | ${d} | ${rest.join(' — ')} | ${n} |\n`; }
md += `\n## Lines\n\n`;
for (const r of rows.sort((a, b) => (a.cls < b.cls ? -1 : 1))) {
  const where = r.inSrc.length ? r.inSrc.join(', ') : r.users.length ? r.users.slice(0, 3).join(', ') + (r.users.length > 3 ? ` (+${r.users.length - 3} more)` : '') : 'none';
  md += `- \`.${r.cls}\` ${r.dir} (${r.when}; searched ${r.tree}) — ${r.kind}: ${where}${r.named.length ? ` — CHANGES.md: ${r.named.slice(0, 3).join(' · ')}` : ''}\n`;
}
writeFileSync(outP, md);
console.log(tally);
