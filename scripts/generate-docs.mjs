#!/usr/bin/env node
/*
 * generate-docs.mjs — writes the generated doc references from source:
 *   skills/dooph-design-system-usage/references/components.md      (exports, props, consts)
 *   skills/dooph-design-system-theming/references/token-contract.md (every token in tokens.css)
 *   .agents/skills/dooph-ds-codebase-map/references/inventory.md    (every src file)
 *   skills/dooph-design-system-setup/references/client-references.md (one generated block)
 *
 * ## behavior
 * - `node scripts/generate-docs.mjs` regenerates all four files and writes the
 *   ones that changed.
 * - `--check` writes nothing: it regenerates in memory, prints `stale <path>` for
 *   each file that differs from disk (a missing file is stale; CRLF vs LF is
 *   not a difference) and exits 1, or
 *   exits 0 when all are fresh. check-conventions.mjs runs it inside
 *   `npm run lint` ("generated doc references out of date").
 * - components.md: the TS program is built from SOURCE (src/index.ts with the
 *   repo tsconfig) through scripts/lib/surface.mjs, grouped by the folder an
 *   export is declared in; a heading names the group (`Utility: cn` for a
 *   src/utils module), never a path, since the file ships to consumers. Props are the component's OWN props; defaults are the
 *   destructuring defaults of its render function (as written), or the cva
 *   `defaultVariants` entry of the class function a prop is passed to. A prop
 *   whose call signatures carry no JSDoc takes it from the same member of the
 *   exported `<Name>Props` type; an export that casts another declaration
 *   (`const X = XBase as XComponent`) takes that declaration's JSDoc.
 * - token-contract.md: every custom property in src/styles/tokens.css, by the
 *   file's own section headings, with its value in each block.
 * - inventory.md: every file under src/, its exports (read syntactically), its
 *   header contract and its place on the "use client" allowlist, which is read
 *   from scripts/check-conventions.mjs as text. The run fails when the number
 *   of file names read differs from the number of `{ file:` entries.
 * - client-references.md: only the text between the `GENERATED:client-references`
 *   markers is generated; the prose around it is hand-written and kept. Every
 *   value export of src/index.ts is a client reference when the file that
 *   declares it carries "use client" (the module add-use-client.mjs stamps in
 *   dist). Missing markers, or an export declared outside src/, fail the run.
 *
 * ## constraints
 * - Reads source, never dist/: lint runs without a build, and a dist read would
 *   document whatever was last built instead of the code at hand.
 * - Output is deterministic (sorted, no timestamps, no absolute paths): `--check`
 *   compares bytes, so any unstable text makes lint fail at random.
 * - Every fact is derived from the code. Hand-written prose here is limited to
 *   legends that define the columns; never state a rule about the design system
 *   in this file, it cannot be checked against source.
 * - An unknown tokens.css block fails the run instead of being skipped, so a new
 *   block cannot silently drop tokens from the contract.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as S from "./lib/surface.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(REPO, "src");
const BANNER = "<!-- GENERATED by scripts/generate-docs.mjs — do not edit -->";
const posix = (p) => p.split(path.sep).join("/");
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ── Markdown helpers ──────────────────────────────────────────────────────────
/** Inline code, safe inside a table cell. */
function code(s) {
  const t = String(s).replace(/\s+/g, " ").replace(/\|/g, "\\|");
  return t.includes("`") ? "`` " + t + " ``" : "`" + t + "`";
}
/** Prose, safe inside a table cell: pipes escaped, `<` outside code spans escaped. */
function prose(s) {
  return String(s ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, "\\<")))
    .join("")
    .replace(/\|/g, "\\|");
}
/** No trailing spaces, at most one blank line in a row, one final newline. */
const finish = (md) => md.replace(/[ \t]+$/gm, "").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
function table(head, rows) {
  if (!rows.length) return "";
  const line = (cells) => `| ${cells.join(" | ")} |`;
  return [line(head), line(head.map(() => "---")), ...rows.map(line)].join("\n") + "\n";
}

// ── components.md ─────────────────────────────────────────────────────────────
const MAX_VALUE = 160;
function constValue(v) {
  if (v.length <= MAX_VALUE) return code(v);
  return /^"/.test(v) ? `a string literal of ${v.length - 2} characters (not shown)` : `${code(v.slice(0, MAX_VALUE))}… (${v.length} characters)`;
}

// Defaults from cva: a call `fooVariants({ variant, size: sizeProp })` inside the
// render function, where fooVariants resolves (through plain aliases) to
// `cva(base, { defaultVariants: {…} })`, gives each prop bound to an option the
// option's default.
function cvaConfigOf(ts, checker, expr, seen = new Set()) {
  if (!expr || seen.has(expr)) return null;
  seen.add(expr);
  if (ts.isIdentifier(expr)) {
    let sym = checker.getSymbolAtLocation(expr);
    if (sym && sym.flags & ts.SymbolFlags.Alias) sym = checker.getAliasedSymbol(sym);
    const d = sym?.valueDeclaration;
    if (!d || !ts.isVariableDeclaration(d) || !S.isOwnFile(d.getSourceFile().fileName, REPO)) return null;
    const name = d.name.getText();
    const init = d.initializer;
    if (init && ts.isCallExpression(init) && ts.isIdentifier(init.expression) && init.expression.text === "cva") {
      const cfg = init.arguments[1];
      if (!cfg || !ts.isObjectLiteralExpression(cfg)) return { name, defaults: {} };
      const dv = cfg.properties.find((p) => ts.isPropertyAssignment(p) && p.name.getText() === "defaultVariants");
      const defaults = {};
      if (dv && ts.isObjectLiteralExpression(dv.initializer))
        for (const p of dv.initializer.properties)
          if (ts.isPropertyAssignment(p)) defaults[p.name.getText()] = S.squash(p.initializer.getText());
      return { name, defaults };
    }
    return init ? cvaConfigOf(ts, checker, init, seen) : null;
  }
  return null;
}
function bindingsOf(ts, fn) {
  // binding name → prop key, for the props parameter's destructuring.
  const out = new Map();
  const p = fn?.parameters?.[0];
  if (!p) return { out, param: null };
  const add = (pat) => {
    for (const el of pat.elements) {
      if (el.dotDotDotToken || !ts.isIdentifier(el.name)) continue;
      out.set(el.name.text, el.propertyName ? el.propertyName.getText() : el.name.text);
    }
  };
  if (ts.isObjectBindingPattern(p.name)) add(p.name);
  else if (ts.isIdentifier(p.name) && fn.body && ts.isBlock(fn.body))
    for (const st of fn.body.statements)
      if (ts.isVariableStatement(st))
        for (const d of st.declarationList.declarations)
          if (ts.isObjectBindingPattern(d.name) && d.initializer && ts.isIdentifier(d.initializer) && d.initializer.text === p.name.text) add(d.name);
  return { out, param: ts.isIdentifier(p.name) ? p.name.text : null };
}
function extractCvaDefaults(ts, checker, fn) {
  const res = {};
  if (!fn?.body) return res;
  const { out: binds, param } = bindingsOf(ts, fn);
  const visit = (n) => {
    if (ts.isCallExpression(n) && n.arguments.length === 1 && ts.isObjectLiteralExpression(n.arguments[0])) {
      const cfg = cvaConfigOf(ts, checker, n.expression);
      if (cfg)
        for (const p of n.arguments[0].properties) {
          let key, val;
          if (ts.isShorthandPropertyAssignment(p)) (key = p.name.text), (val = p.name);
          else if (ts.isPropertyAssignment(p)) (key = p.name.getText()), (val = p.initializer);
          else continue;
          if (!(key in cfg.defaults)) continue;
          let prop = null;
          if (ts.isIdentifier(val) && binds.has(val.text)) prop = binds.get(val.text);
          else if (param && ts.isPropertyAccessExpression(val) && ts.isIdentifier(val.expression) && val.expression.text === param) prop = val.name.text;
          if (prop && !(prop in res)) res[prop] = { value: cfg.defaults[key], via: cfg.name };
        }
    }
    ts.forEachChild(n, visit);
  };
  visit(fn.body);
  return res;
}

// Defaults a component inherits by forwarding its props: exactly one JSX
// element in the render function spreads the props parameter (or the rest of
// its destructuring) into another of this package's components, and that
// component destructures a default for a prop that is forwarded (not taken out
// by the destructuring and not set as an attribute on that element).
function forwardedDefaults(ts, checker, fn, depth = 0) {
  const res = {};
  if (!fn?.body || depth > 4) return res;
  const p = fn.parameters?.[0];
  if (!p) return res;
  let spreadName = null;
  const takenOut = new Set();
  if (ts.isIdentifier(p.name)) spreadName = p.name.text;
  else if (ts.isObjectBindingPattern(p.name))
    for (const el of p.name.elements) {
      if (el.dotDotDotToken && ts.isIdentifier(el.name)) spreadName = el.name.text;
      else takenOut.add(el.propertyName ? el.propertyName.getText() : el.name.getText());
    }
  if (!spreadName) return res;
  const hits = [];
  const visit = (n) => {
    if (ts.isJsxSelfClosingElement(n) || ts.isJsxOpeningElement(n)) {
      const attrs = n.attributes.properties;
      if (attrs.some((a) => ts.isJsxSpreadAttribute(a) && ts.isIdentifier(a.expression) && a.expression.text === spreadName)) hits.push(n);
    }
    ts.forEachChild(n, visit);
  };
  visit(fn.body);
  if (hits.length !== 1) return res;
  const el = hits[0];
  const target = S.findRenderFunction(ts, checker, el.tagName, REPO);
  if (!target) return res;
  const set = new Set(el.attributes.properties.filter((a) => ts.isJsxAttribute(a)).map((a) => a.name.getText()));
  const name = el.tagName.getText();
  const inner = { ...forwardedDefaults(ts, checker, target, depth + 1) };
  for (const [k, v] of Object.entries(S.extractDefaults(ts, target))) inner[k] = { value: v, via: name };
  for (const [k, d] of Object.entries(inner)) if (!takenOut.has(k) && !set.has(k)) res[k] = d;
  return res;
}

// Fallbacks for docs a call signature hides. An overloaded component
// (CTAButton) redeclares props in each signature without JSDoc, so a prop
// whose signatures carry no doc takes the sentence from the same member of the
// exported `<Name>Props` type. An export that is a cast of another declaration
// (`const CTAButton = CTAButtonBase as CTAButtonComponent`) takes the
// component sentence from the declaration it casts.
function propsTypeDocs(ts, checker, exps, name) {
  const p = exps.find((x) => x.name === `${name}Props` && (x.kind === "type" || x.alsoType));
  if (!p) return {};
  const out = {};
  for (const m of checker.getPropertiesOfType(checker.getDeclaredTypeOfSymbol(p.sym))) {
    const own = (m.getDeclarations() ?? []).some((d) => S.isOwnFile(d.getSourceFile().fileName, REPO));
    const doc = own ? ts.displayPartsToString(m.getDocumentationComment(checker)) : "";
    if (doc.trim()) out[m.getName()] = S.firstSentence(doc);
  }
  return out;
}
function componentDoc(ts, checker, sym, depth = 0) {
  const doc = S.symbolDoc(ts, checker, sym);
  if (doc || depth > 4) return doc;
  const d = sym.valueDeclaration;
  let init = d && ts.isVariableDeclaration(d) ? d.initializer : null;
  while (init && (ts.isAsExpression(init) || ts.isParenthesizedExpression(init) || ts.isNonNullExpression(init) || (ts.isSatisfiesExpression && ts.isSatisfiesExpression(init))))
    init = init.expression;
  if (!init || !ts.isIdentifier(init)) return "";
  let src = checker.getSymbolAtLocation(init);
  if (src && src.flags & ts.SymbolFlags.Alias) src = checker.getAliasedSymbol(src);
  const sd = src?.valueDeclaration;
  if (!sd || !S.isOwnFile(sd.getSourceFile().fileName, REPO)) return "";
  return componentDoc(ts, checker, src, depth + 1);
}

function generateComponents() {
  const ts = S.loadTs(REPO);
  const pass1 = S.createSourceProgram(ts, REPO);
  const specs = S.probeSpecs(ts, pass1.checker, S.extractExports(ts, pass1.checker, pass1.sf, REPO, SRC));
  const { checker, sf, probe } = S.createSourceProgram(ts, REPO, specs, pass1.program);
  const exps = S.extractExports(ts, checker, sf, REPO, SRC);
  const { probeTypes, probeTypeAliases } = S.readProbe(checker, probe);

  const groups = new Map();
  for (const e of exps) {
    if (!groups.has(e.module)) groups.set(e.module, []);
    groups.get(e.module).push(e);
  }
  // This file ships in the package, whose reader has no src/, no scripts/ and no
  // `npm run lint`: a group is named (the component folder, or `Utility: cn`),
  // never given as a path.
  const labelOf = (mod) => (mod.includes("/") ? `Utility: ${mod.split("/").pop()}` : mod);

  let md = `${BANNER}\n\n# Components and exports\n\n`;
  md += "Every export of `@dooph-software/design-system`, grouped by the component family (or utility) that declares it.\n\n";
  md += "How to read it:\n\n";
  md += "- **Props** are the component's own props: the ones declared in this package. Props it inherits (DOM attributes, Radix props) are counted under the table, with the packages that declare them.\n";
  md += "- `name?` marks an optional prop. A type with ` / ` between parts means the prop is declared differently in different variants of the props (a union of prop shapes, or several call signatures).\n";
  md += "- **Default** is the default written in the component's render function, as source (`size = ButtonSize.standard`), never an evaluated value. `(cva: fooVariants)` marks a default that comes from the `defaultVariants` of the class function the prop is passed to. `(from Inner)` marks a default of another component in this package that the props are spread into unchanged. A blank default means none of these exists; the prop may still fall back in code (`??`, React context, or a wrapped Radix primitive).\n";
  md += "- **Description** is the first sentence of the prop's JSDoc.\n";
  md += "- Components in one group with identical props are listed together.\n\n";

  const groupNames = [...groups.keys()].sort(cmp);
  md += `## Contents\n\n${groupNames.map(labelOf).map((g) => `[${g}](#${g.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-")})`).join(" · ")}\n\n`;

  for (const g of groupNames) {
    const list = groups.get(g).sort((a, b) => cmp(a.name, b.name));
    const comps = list.filter((e) => e.kind === "component");
    const consts = list.filter((e) => e.kind === "const");
    const fns = list.filter((e) => e.kind === "function");
    const types = list.filter((e) => e.kind === "type" || e.alsoType);
    const others = list.filter((e) => !["component", "const", "function", "type"].includes(e.kind));
    const counts = [
      [comps.length, "component"],
      [consts.length, "const"],
      [types.length, "type"],
      [fns.length, "function"],
      [others.length, "other export"],
    ]
      .filter(([n]) => n)
      .map(([n, w]) => `${n} ${w}${n === 1 ? "" : "s"}`)
      .join(", ");
    md += `## ${labelOf(g)}\n\n${counts}.\n\n`;

    // Components: render each body, then merge identical bodies.
    const bodies = [];
    for (const e of comps) {
      const pr = S.extractProps(ts, checker, e, REPO, probeTypes.get(e.name));
      const docs = S.extractPropDocs(ts, checker, e, REPO);
      const typeDocs = propsTypeDocs(ts, checker, exps, e.name);
      for (const [k, t] of Object.entries(typeDocs)) if (!docs[k]) docs[k] = t;
      const fn = S.findRenderFunction(ts, checker, e.sym.valueDeclaration ?? e.sym.getDeclarations()?.[0], REPO);
      const defs = fn ? S.extractDefaults(ts, fn) : {};
      const cvaDefs = fn ? extractCvaDefaults(ts, checker, fn) : {};
      const fwdDefs = fn ? forwardedDefaults(ts, checker, fn) : {};
      const rows = Object.entries(pr.props).map(([name, p]) => {
        let def = "";
        if (name in defs) def = code(defs[name]);
        else if (name in cvaDefs) def = `${code(cvaDefs[name].value)} (cva: ${cvaDefs[name].via})`;
        else if (name in fwdDefs) def = `${code(fwdDefs[name].value)} (from ${fwdDefs[name].via})`;
        let desc = prose(docs[name] ?? "");
        if (p.deprecated) desc = `**Deprecated.** ${desc}`.trim();
        return [code(name + (p.optional ? "?" : "")), code(p.type), def, desc];
      });
      const own = new Set(Object.keys(pr.props));
      const inhDefaults = Object.entries(defs).filter(([k]) => !own.has(k));
      let body = "";
      body += table(["Prop", "Type", "Default", "Description"], rows);
      if (!rows.length) body += "No own props.\n";
      const facts = [];
      if (pr.inheritedCount) facts.push(`Inherits ${pr.inheritedCount} more prop${pr.inheritedCount === 1 ? "" : "s"}${pr.inheritedFrom.length ? ` from ${pr.inheritedFrom.map(code).join(", ")}` : ""}.`);
      if (pr.refType) facts.push(`\`ref\`: ${code(pr.refType)}.`);
      if (pr.signatures > 1) facts.push(`${pr.signatures} call signatures.`);
      if (pr.generic) facts.push("Generic (polymorphic); inherited props are counted at the default element.");
      if (inhDefaults.length) facts.push(`Defaults for inherited props: ${inhDefaults.map(([k, v]) => code(`${k} = ${v}`)).join(", ")}.`);
      if (facts.length) body += `\n${facts.join(" ")}\n`;
      const doc = componentDoc(ts, checker, e.sym);
      bodies.push({ name: e.name, deprecated: e.deprecated, doc, body });
    }
    const byBody = new Map();
    for (const b of bodies) {
      const k = b.doc + "\0" + b.body;
      if (!byBody.has(k)) byBody.set(k, []);
      byBody.get(k).push(b);
    }
    for (const same of byBody.values()) {
      const names = same.map((b) => b.name);
      const dep = same.some((b) => b.deprecated) ? " (deprecated)" : "";
      if (same.length === 1) md += `### ${names[0]}${dep}\n\n`;
      else md += `### ${names[0]} and ${names.length - 1} more, same props${dep}\n\n${names.map(code).join(", ")}\n\n`;
      if (same[0].doc) md += `${prose(same[0].doc)}\n\n`;
      md += same[0].body + "\n";
    }

    if (consts.length) {
      md += `### Consts\n\n`;
      for (const e of consts) {
        const entries = S.extractConstEntries(ts, checker, e, REPO);
        const keys = Object.keys(entries);
        const tags = [e.alsoType ? "also a type" : "", e.deprecated ? "deprecated" : ""].filter(Boolean).join(", ");
        const head = `${code(e.name)}${tags ? ` (${tags})` : ""}`;
        const doc = S.symbolDoc(ts, checker, e.sym);
        if (keys.length === 1 && keys[0] === "(value)") {
          md += `- ${head}: ${constValue(entries["(value)"])}${doc ? `. ${prose(doc)}` : ""}\n`;
        } else {
          md += `- ${head}${doc ? `: ${prose(doc)}` : ""}\n\n`;
          md += table(["Key", "Value"], keys.map((k) => [code(k), constValue(entries[k])])).replace(/^/gm, "  ") + "\n";
        }
      }
      md += "\n";
    }

    if (types.length) {
      md += `### Types\n\n`;
      for (const e of types) {
        const t = S.extractType(ts, checker, e, REPO, probeTypeAliases.get(e.name));
        const name = t.generics ? `${e.name}<${t.generics}>` : e.name;
        const exp = t.expanded;
        // A generic type is shown by name only: its expansion is the probe's instantiation.
        const show = !t.generics && exp && exp !== e.name && !exp.startsWith("{") && exp.length <= MAX_VALUE;
        md += `- ${code(name)}${show ? ` = ${code(exp)}` : ""}${e.deprecated ? " (deprecated)" : ""}\n`;
      }
      md += "\n";
    }

    if (fns.length) {
      md += `### Functions\n\n`;
      for (const e of fns) for (const sig of S.extractFunction(ts, checker, e)) md += `- ${code(e.name + sig)}\n`;
      md += "\n";
    }
    for (const e of others) md += `- ${code(e.name)} (${e.kind})\n`;
  }
  return finish(md);
}

// ── token-contract.md ─────────────────────────────────────────────────────────
// Blocks of tokens.css by path (selectors and at-rules, @layer dropped). Each
// maps to the column its values go in. Anything else fails the run.
const TOKEN_BLOCKS = {
  ":root, .light": { col: "light", label: "light" },
  ":root": { col: "light", label: "expression defaults" },
  ".dark": { col: "dark", label: "dark" },
  "@media (prefers-reduced-motion: reduce) > :root, .light": { col: "reduced", label: "reduced motion" },
  '[data-ds-expression="practical"]': { col: "practical", label: "practical preset" },
};
const MARKER = /^\s*(?:expression|__[A-Z0-9_]+__)\s*$/;

function commentLines(raw) {
  return raw.split("\n").map((l) => l.replace(/^\s*\*?\s?/, "").replace(/\s+$/, ""));
}
/** A section heading comment: its first line is `── Title ───…`. */
function headingOf(c) {
  const lines = commentLines(c.text);
  const first = lines.findIndex((l) => l.trim());
  if (first < 0 || !/^\s*──/.test(lines[first])) return null;
  const title = lines[first].replace(/^\s*─+\s*/, "").replace(/\s*─+\s*$/, "").trim();
  return { title, body: lines.slice(first + 1).join("\n") };
}
const commentSentence = (c) => {
  const h = headingOf(c);
  return S.firstSentence(h ? h.body : commentLines(c.text).join("\n"));
};

function generateTokenContract() {
  const rel = "src/styles/tokens.css";
  const css = fs.readFileSync(path.join(REPO, rel), "utf8");
  const { comments, decls, blankLines } = S.parseCssDecls(css);
  const blockKeyOf = (b) => b.path.filter((p) => !/^@layer\b/.test(p)).join(" > ");

  // Comment roles.
  const trailing = new Set();
  for (const c of comments) {
    const d = decls.find((x) => x.endLine === c.startLine && x.end < c.start && !css.slice(x.end + 1, c.start).trim());
    if (d) {
      trailing.add(c);
      if (/^\s*expression\s*$/.test(c.text)) d.expression = true;
      else d.trailingNote = commentSentence(c);
    }
  }
  const markerLines = new Set();
  for (const c of comments) if (MARKER.test(c.text) && !trailing.has(c)) for (let l = c.startLine; l <= c.endLine; l++) markerLines.add(l);
  const free = comments.filter((c) => !trailing.has(c) && !MARKER.test(c.text));

  // The comment directly above a declaration (marker lines are transparent), in the same block.
  const above = (d) => {
    let l = d.line - 1;
    while (markerLines.has(l)) l--;
    const c = free.find((x) => x.endLine === l);
    return c && c.start > d.block.open ? c : null;
  };
  // The first line of a declaration's blank-line-separated group inside its block.
  const groupStart = (d) => {
    let l = d.line - 1;
    while (l > d.block.openLine && !blankLines.has(l)) l--;
    return l + 1;
  };

  // Sections: the last heading comment before a token's first declaration.
  const headings = free.map((c) => ({ c, h: headingOf(c) })).filter((x) => x.h);
  const sectionAt = (off) => {
    let s = null;
    for (const x of headings) if (x.c.start < off) s = x;
    return s;
  };

  const tokens = new Map(); // prop → row
  const blocksSeen = new Map(); // key → { layer, count }
  for (const d of decls) {
    const key = blockKeyOf(d.block);
    const kind = TOKEN_BLOCKS[key];
    if (!kind) throw new Error(`${rel}: unknown block "${key}" (line ${d.line}); add it to TOKEN_BLOCKS in scripts/generate-docs.mjs`);
    const bs = blocksSeen.get(key) ?? { layer: S.blockLayer(d.block.path), count: 0, label: kind.label, line: d.block.openLine };
    bs.count++;
    blocksSeen.set(key, bs);
    let row = tokens.get(d.prop);
    if (!row) {
      row = { prop: d.prop, first: d, values: {}, notes: {}, expression: false, blocks: [] };
      tokens.set(d.prop, row);
    }
    row.values[kind.col] = d.value;
    row.blocks.push(kind.label);
    if (d.expression) row.expression = true;
    const a = above(d);
    if (kind.col === "light") {
      row.base = d;
      row.baseBlock = key;
    } else if (a) row.notes[kind.col] = commentSentence(a);
    if (d.trailingNote) row.notes[kind.col + "Trailing"] = d.trailingNote;
  }

  // Group comments and row comments for the base declarations.
  // A group-opening comment covers the declarations after it up to the next
  // comment. Covering exactly one, it is that row's comment; covering none or
  // several, it is shown above the group. Headings become section intros.
  const rowComment = new Map();
  const groupNote = new Map(); // groupKey → sentence
  const groupKey = (d) => `${d.block.open}:${groupStart(d)}`;
  const baseDecls = decls.filter((d) => TOKEN_BLOCKS[blockKeyOf(d.block)].col === "light");
  for (const d of baseDecls) {
    const a = above(d);
    if (a && !headingOf(a)) rowComment.set(d, a);
  }
  const groups = new Map();
  for (const d of baseDecls) {
    const k = groupKey(d);
    if (!groups.has(k)) groups.set(k, { start: groupStart(d), block: d.block, decls: [] });
    groups.get(k).decls.push(d);
  }
  for (const [k, g] of groups) {
    const opener = free.find((c) => c.startLine === g.start && c.start > g.block.open);
    if (!opener || headingOf(opener)) continue;
    const nextComment = free.filter((c) => c.start > opener.end).sort((x, y) => x.start - y.start)[0];
    const covered = g.decls.filter((d) => d.start > opener.end && (!nextComment || d.start < nextComment.start));
    if (covered.length === 1) continue; // it is that row's comment (already set by `above`)
    groupNote.set(k, commentSentence(opener));
    for (const d of covered) if (rowComment.get(d) === opener) rowComment.delete(d);
  }

  const alias = (v) => (v == null ? "" : /^var\(\s*--[\w-]+\s*\)$/.test(v) ? "alias" : /var\(\s*--/.test(v) ? "derived" : "");

  // Render.
  let md = `${BANNER}\n\n# Token contract\n\n`;
  // Consumer-facing text: this file ships in the package, whose reader has no
  // src/, no scripts/ and no `npm run lint`. Name only what the package holds.
  md += "Every DS token (a custom property) in `@dooph-software/design-system/styles.css`, under the DS's own section headings and in its source order.\n\n";
  md += "## Blocks\n\n";
  md += table(
    ["Block", "Selector", "Cascade layer", "Declarations"],
    [...blocksSeen.entries()]
      .sort((a, b) => a[1].line - b[1].line)
      .map(([key, b]) => [b.label, code(key), b.layer ? code(b.layer) : "none", String(b.count)]),
  );
  md += "\n## How to read the tables\n\n";
  md += "- **Light**: the value in `:root, .light`, or in the `:root`-only block for the expression defaults.\n";
  md += "- **Dark**: the value in `.dark`. `same` means `.dark` does not declare it, so the light value applies in dark too. `repeated` means `.dark` declares the identical text again, which re-resolves an alias inside a nested `.dark` region.\n";
  md += "- **Reduced motion** and **Practical preset** columns appear only in sections where a token is also set in that block.\n";
  md += "- **Alias**: `alias` when the light value is exactly one `var()`; `derived` when it computes from other tokens (a `var()` inside `calc()`, `color-mix()` or a shadow).\n";
  md += "- **Expression**: `yes` for an expression token, one the practical preset sets to its neutral value.\n";
  md += "- **Comment**: the first sentence of the comment directly above the token. A comment that opens a group of tokens (lines between blank lines) and covers more than one of them is shown above that group's table instead. `Dark:` is the comment directly above the token's `.dark` line.\n";

  // Section → groups → rows, in document order of base declarations.
  const ordered = [...tokens.values()].sort((a, b) => a.first.start - b.first.start);
  let curSection = undefined;
  let curGroup = undefined;
  let pending = [];
  const flush = () => {
    if (!pending.length) return;
    const has = (col) => pending.some((r) => r.values[col] != null);
    const head = ["Token", "Light", "Dark"];
    if (has("reduced")) head.push("Reduced motion");
    if (has("practical")) head.push("Practical preset");
    head.push("Alias", "Expression", "Comment");
    const rows = pending.map((r) => {
      const light = r.values.light;
      const dark = r.values.dark == null ? (light == null ? "" : "same") : r.values.dark === light ? "repeated" : code(r.values.dark);
      const cells = [code(r.prop), light == null ? "" : code(light), dark];
      if (has("reduced")) cells.push(r.values.reduced == null ? "" : code(r.values.reduced));
      if (has("practical")) cells.push(r.values.practical == null ? "" : code(r.values.practical));
      const notes = [];
      const rc = r.base && rowComment.get(r.base);
      if (rc) notes.push(prose(commentSentence(rc)));
      if (r.notes.lightTrailing) notes.push(prose(r.notes.lightTrailing));
      if (r.notes.dark) notes.push(`Dark: ${prose(r.notes.dark)}`);
      cells.push(alias(light), r.expression ? "yes" : "", notes.join(" "));
      return cells;
    });
    md += table(head, rows) + "\n";
    pending = [];
  };
  for (const r of ordered) {
    const sec = sectionAt(r.first.start);
    if (sec !== curSection) {
      flush();
      curSection = sec;
      curGroup = undefined;
      md += `\n## ${sec ? prose(sec.h.title) : "Before the first heading"}\n\n`;
      const intro = sec ? S.firstSentence(sec.h.body) : "";
      if (intro) md += `${prose(intro)}\n\n`;
      const inSection = ordered.filter((x) => sectionAt(x.first.start) === sec);
      const blocks = [...new Set(inSection.map((x) => x.baseBlock).filter(Boolean))];
      if (blocks.length) md += `Declared in ${blocks.map(code).join(", ")}.\n\n`;
    }
    const gk = r.base ? groupKey(r.base) : `nobase:${r.prop}`;
    if (gk !== curGroup) {
      if (groupNote.has(gk)) {
        flush();
        md += `${prose(groupNote.get(gk))}\n\n`;
      }
      curGroup = gk;
    }
    pending.push(r);
  }
  flush();
  return finish(md);
}

// ── inventory.md ──────────────────────────────────────────────────────────────
function useClientAllowlist() {
  const src = fs.readFileSync(path.join(REPO, "scripts/check-conventions.mjs"), "utf8");
  const m = src.match(/const USE_CLIENT_ALLOWLIST = \[([\s\S]*?)\n\];/);
  if (!m) throw new Error("scripts/check-conventions.mjs: USE_CLIENT_ALLOWLIST not found");
  const files = [...m[1].matchAll(/\bfile:\s*"([^"]+)"/g)].map((x) => x[1]);
  // An entry written another way (single quotes, a template, a variable) would
  // drop out of the inventory silently; fail instead.
  const entries = [...m[1].matchAll(/\{\s*file:/g)].length;
  if (files.length !== entries)
    throw new Error(`scripts/check-conventions.mjs: read ${files.length} file names from ${entries} USE_CLIENT_ALLOWLIST entries; write each as { file: "src/…", … }`);
  return new Set(files);
}

function exportsOf(ts, file, text) {
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, false, file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const out = [];
  const has = (n, k) => n.modifiers?.some((m) => m.kind === k);
  for (const st of sf.statements) {
    const exported = has(st, ts.SyntaxKind.ExportKeyword);
    const isDefault = has(st, ts.SyntaxKind.DefaultKeyword);
    if (ts.isExportDeclaration(st)) {
      const from = st.moduleSpecifier ? ` from ${st.moduleSpecifier.text}` : "";
      if (!st.exportClause) out.push(`*${from}`);
      else if (ts.isNamespaceExport(st.exportClause)) out.push(`* as ${st.exportClause.name.text}${from}`);
      else for (const el of st.exportClause.elements) out.push(el.name.text + (st.isTypeOnly || el.isTypeOnly ? " (type)" : ""));
    } else if (ts.isExportAssignment(st)) out.push("default");
    else if (exported) {
      if (isDefault) out.push("default");
      else if (ts.isVariableStatement(st)) for (const d of st.declarationList.declarations) out.push(d.name.getText(sf));
      else if (st.name) {
        const type = ts.isInterfaceDeclaration(st) || ts.isTypeAliasDeclaration(st);
        out.push(st.name.text + (type ? " (type)" : ""));
      }
    }
  }
  return out;
}

// The same directive test as check-conventions.mjs: a byte-order mark or indentation may precede it.
const USE_CLIENT = /^\uFEFF?[ \t]*["']use client["'];?/m;
function headerContract(text) {
  const m = text.match(/^﻿?\s*(?:(["'])use client\1;?\s*)?(\/\*[\s\S]*?\*\/)/);
  if (!m) return "";
  const b = /##\s*behavior\b/.test(m[2]);
  const c = /##\s*constraints\b/.test(m[2]);
  return b && c ? "behavior, constraints" : b ? "behavior" : c ? "constraints" : "";
}

function generateInventory() {
  const ts = S.loadTs(REPO);
  const allow = useClientAllowlist();
  const files = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else files.push(posix(path.relative(REPO, p)));
    }
  };
  walk(SRC);
  files.sort(cmp);
  const byDir = new Map();
  for (const f of files) {
    const dir = path.posix.dirname(f);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(f);
  }
  let total = { files: 0, contracts: 0, client: 0 };
  let body = "";
  for (const dir of [...byDir.keys()].sort(cmp)) {
    const rows = [];
    for (const f of byDir.get(dir)) {
      const text = fs.readFileSync(path.join(REPO, f), "utf8");
      const isTs = /\.(tsx?|mts|cts)$/.test(f);
      const exps = isTs ? exportsOf(ts, f, text) : [];
      const contract = /\.(tsx?|css|mjs)$/.test(f) ? headerContract(text) : "";
      const directive = isTs && USE_CLIENT.test(text.replace(/\/\*[\s\S]*?\*\//g, ""));
      const listed = allow.has(f);
      const uc = listed && directive ? "yes" : listed ? "listed, no directive" : directive ? "directive, not listed" : "";
      total.files++;
      if (contract) total.contracts++;
      if (listed) total.client++;
      rows.push([code(path.posix.basename(f)), exps.length ? exps.map(code).join(", ") : "", contract, uc]);
    }
    body += `## ${dir}/\n\n` + table(["File", "Exports", "Header contract", '"use client" allowlist'], rows) + "\n";
  }
  let md = `${BANNER}\n\n# Source inventory\n\n`;
  md += "Every file under `src/`, by directory. Generated by `scripts/generate-docs.mjs`; `npm run lint` fails when this file is out of date.\n\n";
  md += `${total.files} files; ${total.contracts} open with a header contract; ${total.client} are on the "use client" allowlist.\n\n`;
  md += "- **Exports**: what the file itself exports, read from its syntax. `* from ./x` is a re-export of everything in `./x`; `(type)` marks a type-only export.\n";
  md += "- **Header contract**: the file opens with a block comment holding `## behavior` and/or `## constraints` (named here).\n";
  md += '- **"use client" allowlist**: `yes` when the file is on the allowlist in `scripts/check-conventions.mjs` and carries the directive. Any other value is a state lint rejects.\n\n';
  return finish(md + body);
}

// ── client-references.md (a generated block inside a hand-written file) ──────
const CLIENT_REFS = "skills/dooph-design-system-setup/references/client-references.md";
const BLOCK_START = "<!-- GENERATED:client-references by scripts/generate-docs.mjs — do not edit -->";
const BLOCK_END = "<!-- /GENERATED:client-references -->";
function generateClientReferences() {
  const ts = S.loadTs(REPO);
  const { checker, sf } = S.createSourceProgram(ts, REPO);
  const exps = S.extractExports(ts, checker, sf, REPO, SRC).filter((e) => e.kind !== "type" && e.kind !== "other");
  const isClient = new Map();
  const client = new Map();
  const serverComponents = [];
  let serverCount = 0;
  for (const e of exps) {
    const decl = e.sym.valueDeclaration ?? e.sym.getDeclarations()?.[0];
    const file = decl ? posix(path.relative(REPO, decl.getSourceFile().fileName)) : "";
    // A value declared outside src/ would need its own package's boundary read; fail rather than guess.
    if (!file.startsWith("src/")) throw new Error(`client-references: export ${e.name} is not declared under src/ (${file || "no declaration"})`);
    if (!isClient.has(file)) {
      const text = fs.readFileSync(path.join(REPO, file), "utf8");
      isClient.set(file, USE_CLIENT.test(text.replace(/\/\*[\s\S]*?\*\//g, "")));
    }
    if (isClient.get(file)) {
      if (!client.has(e.module)) client.set(e.module, []);
      client.get(e.module).push(e);
    } else {
      serverCount++;
      if (e.kind === "component") serverComponents.push(e.name);
    }
  }
  const clientAll = [...client.values()].flat();
  const nonComponents = clientAll.filter((e) => e.kind !== "component").map((e) => e.name).sort(cmp);
  const rows = [...client.keys()].sort(cmp).map((mod) => [code(mod), client.get(mod).map((e) => e.name).sort(cmp).map(code).join(", ")]);
  let block = `${BLOCK_START}\n\n`;
  block += `${exps.length} runtime exports: ${clientAll.length} client references, ${serverCount} server-safe. Read from source: an export is a client reference when the file that declares it carries \`"use client"\`.\n\n`;
  block += "### Client references, by folder\n\n" + table(["Folder", "Exports"], rows) + "\n";
  block += `Client exports that are not components: ${nonComponents.length ? nonComponents.map(code).join(", ") : "none"}. Every other const and function export is server-safe.\n\n`;
  block += "### Server-safe components\n\n" + serverComponents.sort(cmp).map(code).join(", ") + "\n\n";
  block += BLOCK_END;
  const abs = path.join(REPO, CLIENT_REFS);
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8").replace(/\r\n/g, "\n") : "";
  const start = current.indexOf(BLOCK_START);
  const end = current.indexOf(BLOCK_END);
  if (start < 0 || end < start) throw new Error(`${CLIENT_REFS}: generated-block markers not found`);
  return current.slice(0, start) + block + current.slice(end + BLOCK_END.length);
}

